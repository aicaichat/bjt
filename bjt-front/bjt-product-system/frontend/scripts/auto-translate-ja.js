#!/usr/bin/env node
/*
  Auto translate missing Japanese keys using OpenAI.
  Usage: node frontend/scripts/auto-translate-ja.js
  Requires: OPENAI_API_KEY env var, untranslated.csv generated by scanner.
*/

import fs from 'fs/promises';
import path from 'path';
import { fileURLToPath } from 'url';
// eslint-disable-next-line import/no-extraneous-dependencies
import { parse } from 'csv-parse/sync';
import fetch from 'node-fetch';

const __dirname = path.dirname(fileURLToPath(import.meta.url));

const INPUT_CSV = path.resolve(__dirname, '../../untranslated.csv');
const LOCALES_DIR = path.resolve(__dirname, '../src/i18n/locales');
const TARGET_LANG = 'ja';
const RATE_LIMIT_DELAY = 400; // ms between API calls
const MODEL = process.env.OPENAI_MODEL || 'gpt-4o-mini';

async function translateText(text) {
  // Use unofficial Google Translate endpoint (gtx) – no API key required.
  const url =
    'https://translate.googleapis.com/translate_a/single?client=gtx&dt=t&sl=zh-CN&tl=ja&q=' +
    encodeURIComponent(text);
  try {
    const res = await fetch(url);
    const json = await res.json();
    // google returns [[["translated","original",null,null,...]],null,"zh-CN"]
    const translated = json?.[0]?.map((seg) => seg[0]).join('').trim();
    return translated || text;
  } catch (e) {
    console.warn('❌ translate error, fallback to source', e);
    return text;
  }
}

async function run() {
  const canTranslate = true; // always translate via google endpoint

  let csvRaw;
  try {
    csvRaw = await fs.readFile(INPUT_CSV, 'utf8');
  } catch {
    console.error(`❌ ${INPUT_CSV} not found. Run scanner first.`);
    process.exit(1);
  }

  const rows = parse(csvRaw, { columns: true, skip_empty_lines: true });
  if (!rows.length) {
    console.log('✨ No untranslated keys.');
    return;
  }

  // Group by namespace => { key: zhText }
  const groups = {};
  for (const r of rows) {
    if (!groups[r.namespace]) groups[r.namespace] = {};
    groups[r.namespace][r.key] = r.zh;
  }

  for (const ns of Object.keys(groups)) {
    const dstFile = path.join(LOCALES_DIR, TARGET_LANG, `${ns}.json`);
    await fs.mkdir(path.dirname(dstFile), { recursive: true });
    let dstJson = {};
    try {
      dstJson = JSON.parse(await fs.readFile(dstFile, 'utf8'));
    } catch {}

    for (const [key, zhText] of Object.entries(groups[ns])) {
      if (dstJson[key]) continue; // already translated
      console.log(`🔄 Translating [${ns}] ${key}`);
      try {
        dstJson[key] = await translateText(zhText);
      } catch {
        dstJson[key] = zhText;
      }
      if (RATE_LIMIT_DELAY) await new Promise((r) => setTimeout(r, RATE_LIMIT_DELAY));
    }

    await fs.writeFile(dstFile, JSON.stringify(dstJson, null, 2));
    console.log(`✅  Saved ${dstFile}`);
  }

  console.log('🎉 Japanese translation completed');
}

run(); 